def _build_file_payload(
    path: Path,
    *,
    output_delivery: str,
    agent_id: str,
    public_base_url: str | None = None,
) -> Dict[str, Any]:
    mime_type = _mime_type_for_path(path)
    base_payload = {
        "kind": "embedded_file",
        "filename": path.name,
        "format": path.suffix.lstrip(".").lower() or None,
        "mime_type": mime_type,
        "size_bytes": path.stat().st_size,
        "_local_path": str(path),
    }

    if output_delivery == "url":
        return {
            "kind": "downloadable_file",
            "filename": path.name,
            "format": base_payload["format"],
            "mime_type": mime_type,
            "size_bytes": base_payload["size_bytes"],
            "url": f"{_public_base_url(public_base_url)}/agents/{agent_id}/data/{path.name}",
            "_local_path": str(path),
        }

    payload = path.read_bytes()
    how_to_open, python_loader_example = _python_loader_example(
        path.name,
        path.suffix.lstrip(".").lower() or None,
        mime_type,
    )
    return {
        **base_payload,
        "encoding": "base64",
        "data": base64.b64encode(payload).decode("ascii"),
        "how_to_open": how_to_open,
        "python_loader_example": python_loader_example,
    }


def _should_preserve_branch(ancestry: Tuple[str, ...]) -> bool:
    excluded_prefixes = (
        ("inputs",),
        ("complementary", "Execution", "Inputs"),
    )
    return any(ancestry[: len(prefix)] == prefix for prefix in excluded_prefixes)


def _transform_output_files(
    value: Any,
    *,
    agent_id: str,
    output_delivery: str,
    public_base_url: str | None = None,
    key_name: str = "",
    ancestry: Tuple[str, ...] = (),
    relocated_files: Dict[str, Dict[str, Any]] | None = None,
) -> Any:
    if relocated_files is None:
        relocated_files = {}
    if _should_preserve_branch(ancestry):
        return value

    if isinstance(value, str):
        key_lower = key_name.lower()
        if (
            _is_local_file_reference(value)
            and any(token in key_lower for token in ("path", "file", "output", "artifact", "downloaded"))
        ):
            original_path = Path(value).expanduser()
            if not _is_relocatable_output_file(original_path):
                return value
            cache_key = str(original_path.resolve())
            if cache_key in relocated_files:
                payload = dict(relocated_files[cache_key])
            else:
                relocated_path = _relocate_output_file(value, agent_id)
                payload = _build_file_payload(
                    relocated_path,
                    output_delivery=output_delivery,
                    agent_id=agent_id,
                    public_base_url=public_base_url,
                )
                payload["_original_filename"] = original_path.name
                payload["_original_path"] = str(original_path)
                relocated_files[cache_key] = dict(payload)
            artifact_role = _artifact_role_from_key(key_name)
            payload["_artifact_role"] = artifact_role
            payload["_artifact_label"] = _artifact_label_from_key(artifact_role)
            return payload
        return value

    if isinstance(value, list):
        return [
            _transform_output_files(
                item,
                agent_id=agent_id,
                output_delivery=output_delivery,
                public_base_url=public_base_url,
                key_name=key_name,
                ancestry=ancestry,
                relocated_files=relocated_files,
            )
            for item in value
        ]

    if isinstance(value, dict):
        return {
            key: _transform_output_files(
                item,
                agent_id=agent_id,
                output_delivery=output_delivery,
                public_base_url=public_base_url,
                key_name=key,
                ancestry=ancestry + (key,),
                relocated_files=relocated_files,
            )
            for key, item in value.items()
        }

    return value


def _is_external_html_reference(reference: str) -> bool:
    if not reference:
        return True
    stripped = reference.strip()
    if stripped.startswith(("#", "data:", "mailto:", "tel:", "javascript:")):
        return True
    parsed = urlparse(stripped)
    return bool(parsed.scheme or parsed.netloc)


def _rewrite_html_file_references(result: Dict[str, Any] | None) -> None:
    if not isinstance(result, dict):
        return

    file_payloads = _collect_file_payloads(result)
    reference_urls: Dict[str, str] = {}
    for payload in file_payloads:
        url = payload.get("url")
        if not url:
            continue
        for key in ("filename", "_original_filename"):
            filename = payload.get(key)
            if filename:
                reference_urls[Path(str(filename)).name] = str(url)

    if not reference_urls:
        return

    def replacement(match: re.Match[str]) -> str:
        attr, quote, reference = match.group(1), match.group(2), match.group(3)
        if _is_external_html_reference(reference):
            return match.group(0)
        filename = Path(urlparse(reference).path).name
        public_url = reference_urls.get(filename)
        if not public_url:
            return match.group(0)
        return f"{attr}={quote}{public_url}{quote}"

    def css_replacement(match: re.Match[str]) -> str:
        quote, reference = match.group(1) or "", match.group(2)
        if _is_external_html_reference(reference):
            return match.group(0)
        filename = Path(urlparse(reference).path).name
        public_url = reference_urls.get(filename)
        if not public_url:
            return match.group(0)
        return f"url({quote}{public_url}{quote})"

    for payload in file_payloads:
        if (payload.get("format") or "").lower() not in {"html", "htm"}:
            continue
        local_path = Path(str(payload.get("_local_path") or ""))
        if not local_path.is_file():
            continue
        try:
            html = local_path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        rewritten = re.sub(r"\b(src|href)=(['\"])([^'\"]+)\2", replacement, html)
        rewritten = re.sub(r"url\((['\"]?)([^)'\"\s]+)\1\)", css_replacement, rewritten)
        if rewritten != html:
            local_path.write_text(rewritten, encoding="utf-8")


def _encode_file_payloads_for_delivery(value: Any) -> Any:
    if isinstance(value, dict):
        if value.get("kind") == "downloadable_file":
            local_path = Path(str(value.get("_local_path") or ""))
            if local_path.is_file():
                encoded = _build_file_payload(
                    local_path,
                    output_delivery="encoded",
                    agent_id="",
                )
                encoded["_original_filename"] = value.get("_original_filename")
                encoded["_original_path"] = value.get("_original_path")
                encoded["_artifact_role"] = value.get("_artifact_role")
                encoded["_artifact_label"] = value.get("_artifact_label")
                return encoded
        return {
            key: _encode_file_payloads_for_delivery(item)
            for key, item in value.items()
        }
    if isinstance(value, list):
        return [_encode_file_payloads_for_delivery(item) for item in value]
    return value


def _strip_dataset_paths(value: Any, ancestry: Tuple[str, ...] = ()) -> Any:
    if _should_preserve_branch(ancestry):
        return value
    if isinstance(value, list):
        return [_strip_dataset_paths(item, ancestry=ancestry) for item in value]
    if isinstance(value, dict):
        sanitized: Dict[str, Any] = {}
        for key, item in value.items():
            if key in DATASET_PATH_KEYS:
                if isinstance(item, dict) and item.get("kind") in {"embedded_file", "downloadable_file"}:
                    replacement_key = "dataset" if ancestry[:1] == ("outputs",) else key.replace("_path", "")
                    sanitized[replacement_key] = _strip_dataset_paths(item, ancestry=ancestry + (replacement_key,))
                elif isinstance(item, list) and all(
                    isinstance(part, dict) and part.get("kind") in {"embedded_file", "downloadable_file"}
                    for part in item
                ):
                    replacement_key = "datasets" if ancestry[:1] == ("outputs",) else key
                    sanitized[replacement_key] = _strip_dataset_paths(item, ancestry=ancestry + (replacement_key,))
                continue
            sanitized[key] = _strip_dataset_paths(item, ancestry=ancestry + (key,))
        return sanitized
    return value


def _extract_text_and_input_dataset_paths(payload: Dict[str, Any]) -> Tuple[str, List[str], Dict[str, Any], Dict[str, Any]]:
    raw_message = payload.get("message", payload)
    if isinstance(raw_message, str):
        message: Dict[str, Any] = {"parts": [{"kind": "text", "text": raw_message}]}
    elif isinstance(raw_message, dict):
        message = raw_message
    else:
        raise ValueError("Request body must contain task.instructions, query, or text.")

    # The GAS-native request path uses top-level query/parameters. The message,
    # Params, and parts branches remain as a compatibility adapter for older
    # local tests or direct service clients.
    params: Dict[str, Any] = {}
    if isinstance(payload.get("parameters"), dict):
        params.update(payload["parameters"])
    if isinstance(payload.get("metadata"), dict):
        params.update(payload["metadata"])
    if isinstance(payload.get("Params"), dict):
        params.update(payload["Params"])
    if isinstance(payload.get("params"), dict):
        params.update(payload["params"])
    if isinstance(message.get("parameters"), dict):
        params.update(message["parameters"])
    if isinstance(message.get("metadata"), dict):
        params.update(message["metadata"])
    if isinstance(message.get("Params"), dict):
        params.update(message["Params"])
    if isinstance(message.get("params"), dict):
        params.update(message["params"])
    for field_name in (
        REQUEST_OPENAI_KEY_FIELDS
        + REQUEST_GIBD_KEY_FIELDS
        + REQUEST_OUTPUT_DELIVERY_FIELDS
        + REQUEST_STREAM_FIELDS
        + (INPUT_DATASETS_FIELD, "mode", "model", "source_credentials")
    ):
        if field_name in payload and field_name not in params:
            params[field_name] = payload[field_name]
        if field_name in message and field_name not in params:
            params[field_name] = message[field_name]

    reserved_payload_fields = {"message", "parts", "task", "query", "text", "prompt", "content"}
    for key, value in payload.items():
        if key not in reserved_payload_fields and key not in params:
            params[key] = value

    parts = message.get("parts")
    if not isinstance(parts, list) or not parts:
        fallback_text = _first_present(
            {**payload, **message, **params},
            (
                "query",
                "text",
                "prompt",
                "task",
                "data_request",
                "user_query",
                "input",
                "content",
            ),
        )
        if fallback_text:
            parts = [{"kind": "text", "text": fallback_text}]
            message = {**message, "parts": parts}

    if not isinstance(parts, list) or not parts:
        raise ValueError("Message.parts must be a non-empty list.")

    text_parts: List[str] = []
    input_dataset_strings, input_dataset_objects = _normalize_input_datasets(params.get(INPUT_DATASETS_FIELD))

    for part in parts:
        if not isinstance(part, dict):
            continue

        if isinstance(part.get("text"), str):
            text_parts.append(part["text"])
        elif part.get("kind") == "text" and isinstance(part.get("data"), str):
            text_parts.append(part["data"])

        part_params = None
        if isinstance(part.get("Params"), dict):
            part_params = part["Params"]
        elif isinstance(part.get("params"), dict):
            part_params = part["params"]
        elif isinstance(part.get("metadata"), dict):
            part_params = part["metadata"]

        if isinstance(part_params, dict):
            for field_name in REQUEST_OPENAI_KEY_FIELDS + REQUEST_GIBD_KEY_FIELDS:
                if field_name in part_params and field_name not in params:
                    params[field_name] = part_params[field_name]
            part_strings, part_objects = _normalize_input_datasets(part_params.get(INPUT_DATASETS_FIELD))
            input_dataset_strings.extend(part_strings)
            input_dataset_objects.extend(part_objects)

        if part.get("kind") in {"file", "data"}:
            if isinstance(part.get("data"), dict):
                input_dataset_objects.append(part["data"])
            elif isinstance(part.get("file"), dict):
                input_dataset_objects.append(part["file"])

        for field_name in ("path", "uri", "url", "fileUri"):
            if part.get(field_name):
                input_dataset_strings.extend(_normalize_input_dataset_strings(part.get(field_name)))

    query = "\n".join(piece.strip() for piece in text_parts if piece and piece.strip()).strip()
    if not query:
        raise ValueError("Message.parts must include at least one text part.")

    requested_skill = (
        params.get("skill")
        or params.get("requested_skill")
        or params.get("skillId")
    )
    params["requested_skill"] = requested_skill
    input_dataset_paths = _materialize_dataset_inputs(input_dataset_strings, input_dataset_objects)
    return query, input_dataset_paths, params, message


def _extract_output_text(result: Dict[str, Any]) -> str:
    outputs = result.get("outputs", {})
    return str(outputs.get("text") or result.get("text") or "Task completed.")


def _extract_file_artifacts(result: Dict[str, Any]) -> List[Dict[str, Any]]:
    outputs = result.get("outputs", {})
    candidates: List[Tuple[str, Any]] = list(outputs.items()) if isinstance(outputs, dict) else []
    if isinstance(result, dict):
        candidates.extend((key, value) for key, value in result.items() if key != "outputs")

    seen = set()
    artifacts: List[Dict[str, Any]] = []
    for key, value in candidates:
        key_lower = key.lower()

        if isinstance(value, dict) and value.get("kind") in {"embedded_file", "downloadable_file"}:
            artifacts.append(
                {
                    "name": key,
                    "parts": [{"kind": "data", "data": value}],
                    "metadata": {
                        "filename": value.get("filename"),
                        "mime_type": value.get("mime_type"),
                        "url": value.get("url"),
                    },
                }
            )
            continue

        if isinstance(value, list) and any(
            isinstance(item, dict) and item.get("kind") in {"embedded_file", "downloadable_file"}
            for item in value
        ):
            artifacts.append(
                {
                    "name": key,
                    "parts": [
                        {"kind": "data", "data": item}
                        for item in value
                        if isinstance(item, dict) and item.get("kind") in {"embedded_file", "downloadable_file"}
                    ],
                    "metadata": {"count": len(value)},
                }
            )
            continue

        if not isinstance(value, str):
            continue
        if "path" not in key_lower and "file" not in key_lower and "output" not in key_lower:
            continue
        cleaned = value.strip()
        if not cleaned or cleaned in seen:
            continue
        if not _is_local_file_reference(cleaned):
            continue
        seen.add(cleaned)
        embedded = _embed_file_reference(cleaned)
        artifacts.append(
            {
                "name": key,
                "parts": [{"kind": "data", "data": embedded}],
                "metadata": {
                    "filename": embedded.get("filename"),
                    "mime_type": embedded.get("mime_type"),
                },
            }
        )
    return artifacts


def _nested_get(value: Dict[str, Any] | None, path: Tuple[str, ...], default: Any = None) -> Any:
    current: Any = value
    for key in path:
        if not isinstance(current, dict):
            return default
        current = current.get(key)
    return default if current is None else current


def _first_non_empty(*values: Any) -> Any:
    for value in values:
        if value not in (None, "", [], {}):
            return value
    return None


def _execution_status_for_state(state: str) -> str:
    if state == "TASK_STATE_COMPLETED":
        return "success"
    if state == "TASK_STATE_FAILED":
        return "failed"
    if state == "TASK_STATE_CANCELED":
        return "canceled"
    if state == "TASK_STATE_REJECTED":
        return "rejected"
    return "running"


def _summary_for_empty_result(state: str, error_message: str | None) -> str:
    if error_message:
        return ""
    if state == "TASK_STATE_SUBMITTED":
        return "Task submitted."
    if state == "TASK_STATE_WORKING":
        return "Task is running."
    return "Task completed."


def _collect_file_payloads(value: Any) -> List[Dict[str, Any]]:
    artifacts: List[Dict[str, Any]] = []
    if isinstance(value, dict):
        if value.get("kind") in {"embedded_file", "downloadable_file"}:
            artifacts.append(value)
        for item in value.values():
            artifacts.extend(_collect_file_payloads(item))
    elif isinstance(value, list):
        for item in value:
            artifacts.extend(_collect_file_payloads(item))
    return artifacts



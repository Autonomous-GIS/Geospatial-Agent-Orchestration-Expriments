def _normalize_artifacts(
    result: Dict[str, Any] | None,
    *,
    query: str | None = None,
    credentials: Dict[str, str | None] | None = None,
    input_datasets: List[Dict[str, Any]] | None = None,
) -> List[Dict[str, Any]]:
    if not isinstance(result, dict):
        return []

    context_text = _artifact_context_text(result, query)
    normalized: List[Dict[str, Any]] = []
    seen: set[Tuple[Any, Any, Any]] = set()
    for index, payload in enumerate(_collect_file_payloads(result), start=1):
        key = (payload.get("filename"), payload.get("url"), payload.get("data"))
        if key in seen:
            continue
        seen.add(key)
        inspection = inspect_artifact(payload.get("_local_path"))
        file_format = payload.get("format") or "file"
        role = _semantic_artifact_role(payload, inspection, file_format)
        filename = payload.get("filename")
        from gas_server.core.file_naming import extract_naming_metadata
        naming_meta = extract_naming_metadata(payload.get("_original_filename") or filename or "", context_text)
        artifact_name = _semantic_artifact_name(
            payload,
            inspection,
            role,
            file_format,
            index,
            context_text=context_text,
            credentials=credentials,
            input_datasets=input_datasets,
        )
        normalized.append(
            {
                "name": artifact_name,
                "logical_key": naming_meta["logical_key"],
                "qualifiers": naming_meta["qualifiers"],
                "role": role,
                "format": file_format,
                "description": _semantic_artifact_description(
                    payload,
                    inspection,
                    role,
                    file_format,
                    context_text=context_text,
                    artifact_name=artifact_name,
                    credentials=credentials,
                ),
                "filename": filename,
                "label": payload.get("_artifact_label"),
                "original_filename": payload.get("_original_filename"),
                "type": payload.get("kind"),
                "mime_type": payload.get("mime_type"),
                "size_bytes": payload.get("size_bytes"),
                "url": payload.get("url"),
                "encoding": payload.get("encoding"),
                "data": payload.get("data"),
                **inspection,
            }
        )

    # Attempt to label with AI if query & summary are available
    summary = result.get("outputs", {}).get("text") or result.get("text") or ""
    if query and normalized:
        _ai_label_artifacts(normalized, query, summary, credentials=credentials)

    _dedupe_artifact_names(normalized)
    return normalized


def _normalize_lineage(value: Any) -> List[Any]:
    if isinstance(value, list):
        return value
    if isinstance(value, dict):
        return list(value.values())
    if value:
        return [value]
    return []


def _normalize_data_summary(value: Any) -> Dict[str, Any]:
    if not isinstance(value, dict):
        return {"type": None, "dimensions": None, "feature_count": None}
    return {
        "type": value.get("type"),
        "dimensions": value.get("dimensions"),
        "feature_count": value.get("feature_count"),
    }


def _combined_bbox(bboxes: List[List[float]]) -> List[float] | None:
    if not bboxes:
        return None
    return [
        min(bbox[0] for bbox in bboxes),
        min(bbox[1] for bbox in bboxes),
        max(bbox[2] for bbox in bboxes),
        max(bbox[3] for bbox in bboxes),
    ]


def _valid_summary_bbox(value: Any) -> bool:
    return (
        isinstance(value, list)
        and len(value) == 4
        and all(isinstance(item, (int, float)) for item in value)
        and value[0] <= value[2]
        and value[1] <= value[3]
    )


def _summarize_artifact_metadata(artifacts: List[Dict[str, Any]], legacy_summary: Any = None) -> Dict[str, Any]:
    artifact_types: set[str] = set()
    formats: set[str] = set()
    crs_values: set[str] = set()
    bboxes: List[List[float]] = []
    feature_count_total = 0
    has_feature_counts = False
    has_spatial_metadata = False

    for artifact in artifacts:
        if artifact.get("format"):
            formats.add(str(artifact["format"]))
        metadata = artifact.get("spatial_metadata")
        if not isinstance(metadata, dict):
            continue
        has_spatial_metadata = True
        artifact_type = metadata.get("type")
        if artifact_type:
            artifact_types.add(str(artifact_type))
        crs = metadata.get("crs")
        if crs:
            crs_values.add(str(crs))
        bbox = metadata.get("bbox")
        if _valid_summary_bbox(bbox):
            bboxes.append([float(value) for value in bbox])
        feature_count = metadata.get("feature_count")
        if isinstance(feature_count, (int, float)) and not isinstance(feature_count, bool):
            feature_count_total += int(feature_count)
            has_feature_counts = True

    legacy = _normalize_data_summary(legacy_summary)
    primary_type = _first_non_empty(
        legacy.get("type"),
        next(iter(sorted(artifact_types)), None),
    )
    primary_dimensions = legacy.get("dimensions")
    primary_feature_count = _first_non_empty(
        legacy.get("feature_count"),
        feature_count_total if has_feature_counts else None,
    )

    return {
        "type": primary_type,
        "dimensions": primary_dimensions,
        "feature_count": primary_feature_count,
        "artifact_count": len(artifacts),
        "artifact_types": sorted(artifact_types),
        "formats": sorted(formats),
        "crs": sorted(crs_values),
        "combined_bbox": _combined_bbox(bboxes),
        "has_vector": "vector" in artifact_types,
        "has_raster": "raster" in artifact_types,
        "has_table": "table" in artifact_types,
        "feature_count_total": feature_count_total if has_feature_counts else None,
        "has_spatial_metadata": has_spatial_metadata,
    }


def _normalize_execution_inputs(value: Any) -> Dict[str, Any]:
    if not isinstance(value, dict):
        return {"dataset_paths": [], "parameters": {}}
    dataset_paths = _first_non_empty(
        value.get("dataset_paths"),
        value.get("dataset_path"),
        value.get("input_dataset_path"),
        value.get("datasets"),
        [],
    )
    if not isinstance(dataset_paths, list):
        dataset_paths = [dataset_paths]
    dataset_paths = [path for path in dataset_paths if path is not None]
    parameters = value.get("parameters") if isinstance(value.get("parameters"), dict) else {}
    return {
        "dataset_paths": dataset_paths,
        "parameters": _redact_sensitive(parameters),
    }


def _merge_execution_inputs(primary: Any, fallback: Any) -> Dict[str, Any]:
    primary_inputs = _normalize_execution_inputs(primary)
    fallback_inputs = _normalize_execution_inputs(fallback)
    dataset_paths = _first_non_empty(primary_inputs.get("dataset_paths"), fallback_inputs.get("dataset_paths"), [])
    if dataset_paths is None:
        dataset_paths = []
    if not isinstance(dataset_paths, list):
        dataset_paths = [dataset_paths]
    parameters = {}
    if isinstance(fallback_inputs.get("parameters"), dict):
        parameters.update(fallback_inputs["parameters"])
    if isinstance(primary_inputs.get("parameters"), dict):
        parameters.update(primary_inputs["parameters"])
    return {
        "dataset_paths": dataset_paths,
        "parameters": _redact_sensitive(parameters),
    }


def _normalize_runtime(value: Any) -> Dict[str, Any]:
    runtime = value if isinstance(value, dict) else {}
    libraries = _first_non_empty(
        runtime.get("domain-specific_libraries"),
        runtime.get("domain-specific libraries"),
        runtime.get("domain_specific_libraries"),
        [],
    )
    if not isinstance(libraries, list):
        libraries = [libraries]
    return {
        "python_version": runtime.get("python_version"),
        "domain-specific_libraries": libraries,
    }


def _extract_count(value: Any) -> Any:
    if isinstance(value, dict):
        return _first_non_empty(value.get("count"), value.get("total"), value.get("value"))
    return value


def _normalize_token_count(value: Any) -> int | None:
    if value is None:
        return None
    if isinstance(value, str):
        if value.strip().lower() in {"", "none", "null", "nan", "-"}:
            return None
        try:
            return int(value)
        except ValueError:
            return None
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, (int, float)):
        return int(value)
    return None


def _normalize_token_usage(result: Dict[str, Any]) -> Dict[str, Any]:
    input_tokens = _normalize_token_count(result.get("total_input_tokens"))
    output_tokens = _normalize_token_count(
        _first_non_empty(result.get("total_output_tokens"), result.get("toatal_output_tokens"))
    )
    total_tokens = _normalize_token_count(result.get("total_tokens"))
    if total_tokens is None and input_tokens is not None and output_tokens is not None:
        total_tokens = input_tokens + output_tokens
    return {
        "input_tokens": input_tokens,
        "output_tokens": output_tokens,
        "total_tokens": total_tokens,
    }


def _normalize_iterations(result: Dict[str, Any], metrics: Dict[str, Any], llm_calls: Any, tool_calls: Any) -> Any:
    return _first_non_empty(
        result.get("iterations"),
        metrics.get("iterations"),
        llm_calls,
        tool_calls,
        0,
    )


def _normalize_diagnostics(error_message: str | None, complementary: Dict[str, Any]) -> Dict[str, Any]:
    validation = complementary.get("Validation") if isinstance(complementary.get("Validation"), dict) else {}
    assumptions_limitations = (
        complementary.get("Assumptions and Limitations")
        if isinstance(complementary.get("Assumptions and Limitations"), dict)
        else {}
    )
    warnings: List[str] = []
    for key in ("warnings", "limitations"):
        values = assumptions_limitations.get(key)
        if isinstance(values, list):
            warnings.extend(str(value) for value in values if value)
        elif values:
            warnings.append(str(values))

    return {
        "has_error": bool(error_message),
        "error": error_message,
        "warnings": warnings,
        "validation": validation,
        "assumptions": assumptions_limitations.get("assumptions", []),
        "limitations": assumptions_limitations.get("limitations", []),
    }


def _normalize_reproducibility(
    *,
    execution_inputs: Dict[str, Any],
    runtime: Dict[str, Any],
    normalized_artifacts: List[Dict[str, Any]],
    code: Dict[str, Any],
    result: Dict[str, Any],
) -> Dict[str, Any]:
    input_artifacts = [
        {
            "role": "input",
            "path": path,
        }
        for path in execution_inputs.get("dataset_paths", [])
    ]
    output_artifacts = [
        {
            "role": artifact.get("role") or "output",
            "label": artifact.get("label"),
            "name": artifact.get("name"),
            "original_filename": artifact.get("original_filename"),
            "url": artifact.get("url"),
            "format": artifact.get("format"),
            "type": artifact.get("type"),
        }
        for artifact in normalized_artifacts
    ]
    stochasticity = result.get("stochasticity") if isinstance(result.get("stochasticity"), dict) else {}
    controls = stochasticity.get("controls", [])
    if not isinstance(controls, list):
        controls = [controls]
    normalized_controls = [
        control if isinstance(control, dict) else {"description": str(control)}
        for control in controls
    ]
    return {
        "code_available": bool(code.get("available")),
        "environment_available": bool(runtime.get("python_version") or runtime.get("domain-specific_libraries")),
        "parameters_available": bool(execution_inputs.get("parameters")),
        "input_artifacts": input_artifacts,
        "output_artifacts": output_artifacts,
        "parameters": execution_inputs.get("parameters", {}),
        "stochasticity": {
            "used": stochasticity.get("used", "unknown"),
            "controls": normalized_controls,
        },
        "notes": result.get("reproducibility_notes") if isinstance(result.get("reproducibility_notes"), list) else [],
    }


def _parse_duration_seconds(value: Any) -> float | None:
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, str):
        match = re.search(r"[-+]?\d*\.?\d+", value)
        if match:
            try:
                return float(match.group(0))
            except ValueError:
                return None
    return None


def _normalize_metadata_key(value: str) -> str:
    normalized = re.sub(r"[^a-zA-Z0-9]+", "_", value).strip("_").lower()
    return normalized or "metadata"


def _normalize_provenance_details(complementary_provenance: Dict[str, Any]) -> Dict[str, Any]:
    standard_keys = {"Lineage", "Tool Calls", "LLM Calls"}
    details: Dict[str, Any] = {}
    for key, value in complementary_provenance.items():
        if key in standard_keys:
            continue
        details[_normalize_metadata_key(str(key))] = _remove_stream_event_fields(value)
    return details


def _normalize_agent_result(
    *,
    task_id: str,
    agent_id: str,
    agent_name: str | None,
    agent_version: str | None,
    state: str,
    query: str,
    requested_skill: str | None,
    result: Dict[str, Any] | None,
    error_message: str | None,
    output_delivery: str,
    created_at: str,
    completed_at: str,
    credentials: Dict[str, str | None] | None = None,
    input_datasets: List[Dict[str, Any]] | None = None,
) -> Dict[str, Any]:
    result = result if isinstance(result, dict) else {}
    result = {key: value for key, value in result.items() if key not in {"events", "stream_events", "thinking_events"}}
    outputs = result.get("outputs") if isinstance(result.get("outputs"), dict) else {}
    outputs = {key: value for key, value in outputs.items() if key not in {"events", "stream_events", "thinking_events"}}
    metrics = result.get("metrics") if isinstance(result.get("metrics"), dict) else {}
    complementary = result.get("complementary") if isinstance(result.get("complementary"), dict) else {}
    complementary_outputs = _nested_get(complementary, ("Execution", "Outputs"), {})
    complementary_inputs = _nested_get(complementary, ("Execution", "Inputs"), {})
    complementary_provenance = _nested_get(complementary, ("Provenance",), {})
    environment = result.get("environment") if isinstance(result.get("environment"), dict) else {}
    normalized_artifacts = _normalize_artifacts(result, query=query, credentials=credentials, input_datasets=input_datasets)
    data_summary = _summarize_artifact_metadata(
        normalized_artifacts,
        _first_non_empty(outputs.get("dataset_size"), result.get("dataset_size"), {}),
    )
    execution_inputs = _merge_execution_inputs(complementary_inputs, result.get("inputs"))
    runtime = _normalize_runtime(environment)
    llm_calls = _first_non_empty(
        metrics.get("llm_calls"),
        _extract_count(_nested_get(complementary_provenance, ("LLM Calls",), None)),
        result.get("llm_calls"),
    )
    tool_calls = _first_non_empty(
        metrics.get("tool_calls"),
        _extract_count(_nested_get(complementary_provenance, ("Tool Calls",), None)),
        result.get("tool_calls"),
    )
    token_usage = _normalize_token_usage(result)
    duration_seconds = _parse_duration_seconds(result.get("duration"))
    iterations = _normalize_iterations(result, metrics, llm_calls, tool_calls)
    code = {
        "available": bool(result.get("script")),
        "language": "python" if result.get("script") else None,
        "script": result.get("script"),
    }
    reproducibility = _normalize_reproducibility(
        execution_inputs=execution_inputs,
        runtime=runtime,
        normalized_artifacts=normalized_artifacts,
        code=code,
        result=result,
    )
    provenance_details = _normalize_provenance_details(complementary_provenance)
    provenance = {
        "llm_calls": llm_calls or 0,
        "tool_calls": tool_calls or 0,
        "artifacts_created": _first_non_empty(
            metrics.get("number_of_artifacts"),
            metrics.get("number of artifacts"),
            len(normalized_artifacts),
        ),
        "token_usage": token_usage,
        "lineage": _normalize_lineage(_nested_get(complementary_provenance, ("Lineage",), [])),
    }
    if provenance_details:
        provenance["details"] = provenance_details

    normalized_outputs: Dict[str, Any] = {
        "summary": _first_non_empty(
            outputs.get("text"),
            complementary_outputs.get("summary") if isinstance(complementary_outputs, dict) else None,
            result.get("text"),
            _summary_for_empty_result(state, error_message),
        ),
        "artifacts": normalized_artifacts,
        "data_summary": data_summary,
    }

    # Orchestrator agents return workflow control metadata that the canvas must
    # consume directly. Preserve these fields instead of reducing them to a text
    # summary; otherwise QC/replan responses cannot update the active workflow.
    for key in (
        "verdict",
        "reason",
        "recovery_option",
        "workflow_status",
        "workflow_plan",
        "workflow_json_file",
        "failed_node_id",
        "message",
    ):
        if key in outputs:
            normalized_outputs[key] = outputs[key]

    return {
        "response": {
            "type": "task_result",
            "schema_version": "1.0.0",
            "created_at": created_at,
            "completed_at": completed_at,
        },
        "task": {
            "id": task_id,
            "status": _gas_status_for_state(state),
            "terminal": _is_terminal_state(state),
            "user_request": query,
            "requested_skill": requested_skill,
            "artifact_delivery": "Encoded" if output_delivery == "encoded" else "URL",
        },
        "agent": {
            "id": agent_id,
            "name": _first_non_empty(result.get("agent_name"), agent_name),
            "version": _first_non_empty(result.get("agent_version"), agent_version),
            "model": result.get("model"),
        },
        "outputs": normalized_outputs,
        "execution": {
            "status": _execution_status_for_state(state),
            "duration_seconds": duration_seconds,
            "iterations": iterations,
            "inputs": execution_inputs,
            "code": code,
            "runtime": runtime,
        },
        "provenance": provenance,
        "reproducibility": reproducibility,
        "diagnostics": _normalize_diagnostics(error_message, complementary),
    }


def _remove_stream_event_fields(value: Any) -> Any:
    stream_event_keys = {"events", "stream_events", "thinking_events"}
    if isinstance(value, dict):
        return {
            key: _remove_stream_event_fields(item)
            for key, item in value.items()
            if key not in stream_event_keys
        }
    if isinstance(value, list):
        return [_remove_stream_event_fields(item) for item in value]
    return value


def _build_task_payload(
    *,
    task_id: str,
    agent_id: str,
    agent_name: str | None,
    agent_version: str | None,
    state: str,
    query: str,
    requested_skill: str | None,
    result: Dict[str, Any] | None,
    error_message: str | None,
    agent_id_for_artifacts: str,
    output_delivery: str,
    public_base_url: str | None = None,
    credentials: Dict[str, str | None] | None = None,
    input_datasets: List[Dict[str, Any]] | None = None,
) -> Dict[str, Any]:
    transformed_result = (
        _transform_output_files(
            result,
            agent_id=agent_id_for_artifacts,
            output_delivery="url",
            public_base_url=public_base_url,
        )
        if result is not None
        else None
    )
    _rewrite_html_file_references(transformed_result)
    if output_delivery == "encoded" and transformed_result is not None:
        transformed_result = _encode_file_payloads_for_delivery(transformed_result)
    normalized_result = _strip_dataset_paths(transformed_result) if transformed_result is not None else None

    completed_dt = datetime.now(timezone.utc)
    duration_seconds = _parse_duration_seconds(normalized_result.get("duration") if isinstance(normalized_result, dict) else None)
    created_dt = completed_dt - timedelta(seconds=duration_seconds) if duration_seconds and _is_terminal_state(state) else completed_dt
    created_at = created_dt.isoformat()
    completed_at = completed_dt.isoformat() if _is_terminal_state(state) else None
    task_payload = _normalize_agent_result(
        task_id=task_id,
        agent_id=agent_id,
        agent_name=agent_name,
        agent_version=agent_version,
        state=state,
        query=query,
        requested_skill=requested_skill,
        result=normalized_result,
        error_message=error_message,
        output_delivery=output_delivery,
        created_at=created_at,
        completed_at=completed_at,
        credentials=credentials,
        input_datasets=input_datasets,
    )
    return _remove_stream_event_fields(task_payload)



def _generate_managed_filename(agent_id: str, original_path: Path) -> str:
    ext = original_path.suffix.lower()
    prefix = agent_id.replace(" ", "")
    letters = string.ascii_lowercase

    # Clean the original stem of existing suffix / prefix pattern to avoid nesting
    original_stem = original_path.stem
    original_stem = re.sub(r"-\d{4}-[a-z]{4}-\d{4}$", "", original_stem, flags=re.I)
    if original_stem.startswith(f"{prefix}-"):
        original_stem = original_stem[len(prefix) + 1 :]

    # Sanitize the remaining stem (only alphanumeric and hyphens)
    stem = re.sub(r"[^a-zA-Z0-9-]", "-", original_stem.replace("_", "-")).lower()
    stem = re.sub(r"-+", "-", stem).strip("-")

    prefix_with_stem = f"{prefix}-{stem}" if stem else prefix

    while True:
        candidate = (
            f"{prefix_with_stem}-"
            f"{random.randint(0, 9999):04d}-"
            f"{''.join(random.choice(letters) for _ in range(4))}-"
            f"{random.randint(0, 9999):04d}"
            f"{ext}"
        )
        if not (_agent_data_dir(agent_id) / candidate).exists():
            return candidate


def _relocate_output_file(path_str: str, agent_id: str) -> Path:
    source = Path(path_str).expanduser()
    if not source.is_file() or not _is_relocatable_output_file(source):
        return source

    target_dir = _agent_data_dir(agent_id)
    if source.parent.resolve() == target_dir.resolve():
        return source

    target = target_dir / _generate_managed_filename(agent_id, source)
    shutil.copy2(str(source), str(target))
    return target



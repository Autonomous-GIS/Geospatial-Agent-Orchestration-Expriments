def _is_local_file_reference(value: str) -> bool:
    if not isinstance(value, str):
        return False

    cleaned = value.strip()
    if not cleaned:
        return False

    # Reject obvious non-path payloads before touching the filesystem.
    if len(cleaned) > 512:
        return False
    if cleaned.startswith(("{", "[")):
        return False
    if "://" in cleaned:
        return False
    if "\n" in cleaned or "\r" in cleaned:
        return False
    if "\x00" in cleaned:
        return False
    if not any(token in cleaned for token in (os.sep, "/", "\\", ".")):
        return False

    try:
        path = Path(cleaned).expanduser()
    except (TypeError, ValueError, OSError):
        return False

    try:
        return path.is_file()
    except OSError:
        return False


def _is_relative_to(path: Path, parent: Path) -> bool:
    try:
        path.resolve().relative_to(parent.resolve())
        return True
    except (OSError, ValueError):
        return False


def _is_relocatable_output_file(path: Path) -> bool:
    """Only manage generated runtime artifacts, never arbitrary source files."""
    if not path.is_file():
        return False
    runtime_roots = (DATA_DIR, OUTPUT_DIR)
    if any(_is_relative_to(path, root) for root in runtime_roots):
        return True
    # Test/worker processes may stage generated files in conventional sibling
    # directories before relocation. Accept only those named staging roots,
    # never an arbitrary file elsewhere in the temporary tree.
    return any(parent.name.lower() in {"data", "generated", "outputs"} for parent in path.parents)


def _mime_type_for_path(path: Path) -> str:
    suffix = path.suffix.lower()
    overrides = {
        ".geojson": "application/geo+json",
        ".gpkg": "application/geopackage+sqlite3",
        ".shp": "application/octet-stream",
        ".tif": "image/tiff",
        ".tiff": "image/tiff",
    }
    if suffix in overrides:
        return overrides[suffix]
    guessed, _ = mimetypes.guess_type(path.name)
    return guessed or "application/octet-stream"



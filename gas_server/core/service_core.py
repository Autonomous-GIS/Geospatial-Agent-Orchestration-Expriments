    explicit = payload.get("_artifact_name") or payload.get("display_name")
    if explicit:
        return str(explicit).strip()

    explicit_label = str(payload.get("_artifact_label") or "").strip()
    original_name = payload.get("_original_filename") or payload.get("filename")
    meaningful_stem = _clean_artifact_stem(original_name)
    format_label = _artifact_format_label(file_format)

    # Extract a clean subject hint from the filename, stripping technical
    # operation words (e.g. "projected", "clipped") so the AI naming helper
    # receives a strong anchor for what the data actually represents.
    from gas_server.core.file_naming import extract_subject_hint
    subject_hint = extract_subject_hint(original_name)
    inherited_subject = _lookup_inherited_subject(original_name, input_datasets=input_datasets)
    if inherited_subject:
        subject_hint = inherited_subject
        
